import sys


class ToolkitError(Exception):
    """Базовое исключение для нашего пакета toolkit.

    Мы создаем свой собственный класс ошибки, чтобы вычислительное ядро
    могло сигнализировать CLI-интерфейсу о проблемах (например, о делении на ноль),
    не вызывая при этом падения всей программы.
    """



def handle_error(message: str) -> None:
    """Выводит сообщение об ошибке в stderr и завершает процесс с кодом 2.

    Эта функция вызывается строго на уровне CLI, когда ядро выбросило ToolkitError.
    """
    print(f"Error: {message}", file=sys.stderr)
    sys.exit(2)
